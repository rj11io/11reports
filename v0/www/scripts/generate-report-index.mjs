#!/usr/bin/env node

import { mkdir, writeFile } from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"

import { readBundleArtifacts, validateArchive } from "./lib/report-core.mjs"

const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const contentRoot = path.join(appRoot, "content", "reports")
const indexOutputPath = path.join(appRoot, "lib", "reports", "generated-index.ts")
const contentOutputPath = path.join(appRoot, "lib", "reports", "generated-content.ts")
const validation = await validateArchive(contentRoot)

if (!validation.ok) {
  console.error(validation.errors.join("\n"))
  process.exit(1)
}

const reports = []
const contents = {}
for (const manifest of validation.reports) {
  const bundlePath = path.join(contentRoot, manifest.id)
  reports.push(manifest)
  contents[manifest.id] = await readBundleArtifacts(bundlePath, manifest)
}

reports.sort((left, right) => right.createdAt.localeCompare(left.createdAt))

const indexSource = `// Generated by scripts/generate-report-index.mjs. Do not edit.\n\nexport const generatedReportManifests = ${JSON.stringify(reports, null, 2)} as const\n`
const contentSource = `// Generated by scripts/generate-report-index.mjs. Do not edit.\n\nexport const generatedReportContents = ${JSON.stringify(contents, null, 2)} as const\n`
await mkdir(path.dirname(indexOutputPath), { recursive: true })
await writeFile(indexOutputPath, indexSource)
await writeFile(contentOutputPath, contentSource)
console.log(`Generated ${reports.length} reports at ${path.relative(appRoot, indexOutputPath)}`)
